// Merges probe JSONs (from spectate-probe.mjs) into spectate-grids.js, REPLACING only the maps/sizes probed; keeps the rest.
//   node tools/spectate-build.mjs <griddir>
import fs from 'fs';
const DIR = process.argv[2] || 'grids', FILE = new URL('../spectate-grids.js', import.meta.url).pathname;
const files = fs.readdirSync(DIR).filter((f) => /^[a-z]+-(normal|big)-(high|ultra)\.json$/.test(f));
const by = {};
for (const f of files) { const [m, size] = f.split('-'); (by[`${m}:${size}`] ||= []).push(JSON.parse(fs.readFileSync(`${DIR}/${f}`))); }
const rle = (str) => str.replace(/(.)\1*/g, (r, ch) => (r.length > 1 ? r.length : '') + ch);
const floorCh = (y) => String.fromCharCode(65 + Math.min(15, Math.max(0, Math.round((y + 0.3) / 0.03))));
const src = fs.readFileSync(FILE, 'utf8');
const out = {};
for (const m of src.matchAll(/^ {2}'([a-z]+:[a-z]+)': \['([^']*)', '([^']*)'\],$/gm)) out[m[1]] = [m[2], m[3]];
let G = { X0: -24, Z0: -16, S: 0.5, W: 97, H: 65 };
for (const [k, list] of Object.entries(by)) {
  G = list[0]; const n = G.W * G.H; let wS = '', tS = '';
  for (let i = 0; i < n; i++) {
    let blocked = false, voidy = false, floor = -Infinity, top = -Infinity;
    for (const g of list) {
      const t = g.ys[i], u = g.us[i], f = g.fs[i];
      if (t === null || t < -0.3) { voidy = true; continue; }
      if (t <= 0.15) { floor = Math.max(floor, t); continue; }
      top = Math.max(top, t);
      if (u === null || u < 2.0 || Math.abs(u - t) < 0.35) { blocked = true; continue; }
      if (f !== null && f >= -0.3 && f <= 0.15) floor = Math.max(floor, f); else if (f === null || f < -0.3) voidy = true; else blocked = true;
    }
    wS += blocked ? '#' : voidy ? '_' : floorCh(floor);
    tS += top > -Infinity ? String.fromCharCode(96 + Math.min(26, Math.max(1, Math.ceil(top / 0.5)))) : '.';
  }
  out[k] = [rle(wS), rle(tS)];
}
const js = `// generated by sampling every map's scene (tools/spectate-probe.mjs + spectate-build.mjs) — 0.5 m cells, x ${G.X0}..${-G.X0}, z ${G.Z0}..${-G.Z0}\n` +
  `// per map: [ground — A..P floor height, _ water / drop, # blocked;  scenery top for the camera — a..z (×0.5 m), . nothing]\n` +
  `export const GRID = { X0: ${G.X0}, Z0: ${G.Z0}, S: ${G.S}, W: ${G.W}, H: ${G.H} };\nexport const GRIDS = {\n` +
  Object.keys(out).sort().map((k) => `  '${k}': ['${out[k][0]}', '${out[k][1]}'],`).join('\n') + '\n};\n';
fs.writeFileSync(FILE, js);
console.log(Object.keys(out).length, 'grids:', Object.keys(by).join(' '), 'updated');
